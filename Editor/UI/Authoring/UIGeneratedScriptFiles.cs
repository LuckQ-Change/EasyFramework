using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.Compilation;
using UnityEngine;

namespace EasyFramework.Editor.UI
{
    /// <summary>定位 UI 生成源码、检查目标程序集并维护现有生成资产的路径。</summary>
    internal static class UIGeneratedScriptFiles
    {
        internal const string DefaultFolder = "Assets/GameMain/Runtime/Generated";
        private const string AssemblyReferenceFile = "EasyFramework.UI.asmref";
        internal const string GeneratedHeader = "// <auto-generated />";
        private static readonly Regex SourceGuid = new(@"\.([a-f0-9]{32})\.g\.cs$", RegexOptions.CultureInvariant);
        private static readonly UTF8Encoding Encoding = new(false);

        /// <summary>承载程序集引用文件的序列化内容。</summary>
        [Serializable]
        private sealed class AssemblyReference
        {
            public string reference;
        }

        /// <summary>描述业务脚本对应的生成文件位置和程序集。</summary>
        private readonly struct Route
        {
            internal readonly string Path;
            internal readonly string Assembly;
            internal readonly string DefinitionGuid;

            internal Route(string path, string assembly, string definitionGuid)
            {
                Path = path;
                Assembly = assembly;
                DefinitionGuid = definitionGuid;
            }
        }

        #region 公共方法

        internal static string PathFor(string businessScript, string guid, bool prepare = false)
        {
            string root = UIAuthoringSettings.instance.GeneratedFolder;
            Route route = GetRoute(root, businessScript, guid);
            if (prepare)
            {
                string existingPath = FindExistingPath(root, route, businessScript, guid);
                PrepareRoute(route);
                if (existingPath != null && existingPath != route.Path)
                    Move(existingPath, route.Path);
            }
            else if (File.Exists(route.Path))
                CheckAssembly(route);

            return route.Path;
        }

        #endregion

        #region 私有逻辑

        private static string FindExistingPath(string root, Route route, string businessScript, string guid)
        {
            string[] candidates = OwnedScripts(root, $"*.{guid}.g.cs")
                .Select(file => file.path).OrderBy(path => path, StringComparer.Ordinal).ToArray();
            if (candidates.Length > 1)
                throw new InvalidOperationException($"{businessScript} 有多个生成文件：{string.Join("、", candidates)}。");

            string existingPath = candidates.SingleOrDefault();
            if (File.Exists(route.Path))
            {
                // Windows 下仅有大小写差异的路径可指向同一份已登记资产。
                StringComparison comparison = System.IO.Path.DirectorySeparatorChar == '\\'
                    ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
                if (!IsOwned(route.Path, out string targetGuid) || targetGuid != guid ||
                    (existingPath != null && !string.Equals(existingPath, route.Path, comparison)))
                    throw new InvalidOperationException($"生成文件的目标被占用：{route.Path}。");
                return route.Path;
            }

            if (File.Exists(route.Path + ".meta"))
                throw new InvalidOperationException($"生成文件的目标已有独立元数据：{route.Path}.meta。请恢复对应文件或处理元数据后重试。");

            return existingPath;
        }

        private static Route GetRoute(string root, string businessScript, string guid)
        {
            string assembly = CompilationPipeline.GetAssemblyNameFromScriptPath(businessScript);
            if (string.IsNullOrEmpty(assembly))
                throw new InvalidOperationException($"无法识别业务脚本 {businessScript} 的程序集。");

            string fileName = $"{System.IO.Path.GetFileNameWithoutExtension(businessScript)}.{guid}.g.cs";
            string path = $"{root}/{fileName}";
            if (CompilationPipeline.GetAssemblyNameFromScriptPath(path) == assembly)
                return new Route(path, assembly, null);

            string definition = CompilationPipeline.GetAssemblyDefinitionFilePathFromScriptPath(businessScript);
            string definitionGuid = string.IsNullOrEmpty(definition) ? null : AssetDatabase.AssetPathToGUID(definition);
            if (string.IsNullOrEmpty(definitionGuid))
                throw new InvalidOperationException($"生成目录 {root} 需要与 {businessScript} 一样属于 {assembly}。请选择该程序集下的目录。");

            string folder = System.IO.Path.GetFileNameWithoutExtension(definition) + "." + definitionGuid;
            return new Route($"{root}/{folder}/{fileName}", assembly, definitionGuid);
        }

        private static void PrepareRoute(Route route)
        {
            string referencePath = FindRequiredAssemblyReference(route);
            string folder = route.Path.Substring(0, route.Path.LastIndexOf('/'));
            EnsureFolder(folder);
            if (referencePath != null)
            {
                var reference = new AssemblyReference { reference = "GUID:" + route.DefinitionGuid };
                File.WriteAllText(referencePath, JsonUtility.ToJson(reference, true) + "\n", Encoding);
                AssetDatabase.ImportAsset(referencePath, ImportAssetOptions.ForceSynchronousImport);
            }
            CheckAssembly(route);
        }

        private static string FindRequiredAssemblyReference(Route route)
        {
            if (Directory.Exists(route.Path) || Directory.Exists(route.Path + ".meta"))
                throw new InvalidOperationException($"生成文件的目标已被目录占用：{route.Path}。");
            string folder = route.Path.Substring(0, route.Path.LastIndexOf('/'));
            for (string parent = folder; parent != null;)
            {
                if (File.Exists(parent))
                    throw new InvalidOperationException($"生成目录已被同名文件占用：{parent}。");
                bool hasDirectory = Directory.Exists(parent);
                if (hasDirectory != AssetDatabase.IsValidFolder(parent))
                    throw new InvalidOperationException($"生成目录尚未与 Unity 资产数据库同步：{parent}。请刷新资产后重试。");
                if (!hasDirectory && (File.Exists(parent + ".meta") || Directory.Exists(parent + ".meta")))
                    throw new InvalidOperationException($"生成目录的目标已有独立元数据：{parent}.meta。");
                int separator = parent.LastIndexOf('/');
                parent = separator < 0 ? null : parent.Substring(0, separator);
            }

            if (route.DefinitionGuid == null)
            {
                CheckAssembly(route);
                return null;
            }

            string referencePath = $"{folder}/{AssemblyReferenceFile}";
            if (Directory.Exists(referencePath) || Directory.Exists(referencePath + ".meta"))
                throw new InvalidOperationException($"程序集引用的目标已被目录占用：{referencePath}。");
            bool hasReference = File.Exists(referencePath);
            if (!hasReference && File.Exists(referencePath + ".meta"))
                throw new InvalidOperationException($"程序集引用的目标已有独立元数据：{referencePath}.meta。请恢复对应文件或处理元数据后重试。");

            // 生成子目录只允许一个程序集声明。首次建立引用前还要保护已有业务脚本。
            if (Directory.Exists(folder))
            {
                foreach (string file in Directory.EnumerateFiles(folder))
                {
                    string extension = System.IO.Path.GetExtension(file);
                    bool hasOtherAssembly = string.Equals(extension, ".asmdef", StringComparison.OrdinalIgnoreCase) ||
                        string.Equals(extension, ".asmref", StringComparison.OrdinalIgnoreCase) &&
                        !string.Equals(file.Replace('\\', '/'), referencePath, StringComparison.OrdinalIgnoreCase);
                    bool hasBusinessScript = !hasReference && string.Equals(extension, ".cs", StringComparison.OrdinalIgnoreCase) &&
                        !IsOwned(file, out _);
                    if (hasOtherAssembly || hasBusinessScript)
                        throw new InvalidOperationException($"{file} 与生成目录的程序集引用冲突，请另选生成目录。");
                }
            }

            if (hasReference)
            {
                if (JsonUtility.FromJson<AssemblyReference>(File.ReadAllText(referencePath))?.reference != "GUID:" + route.DefinitionGuid)
                    throw new InvalidOperationException($"{referencePath} 未引用目标程序集。");
                CheckAssembly(route);
                return null;
            }

            return referencePath;
        }

        private static void CheckAssembly(Route route)
        {
            if (CompilationPipeline.GetAssemblyNameFromScriptPath(route.Path) != route.Assembly)
                throw new InvalidOperationException($"生成文件 {route.Path} 必须编译进 {route.Assembly}，请检查目录的程序集设置。");
        }

        #endregion

        #region 公共方法

        internal static string ChangeFolder(string current, string requested)
        {
            string next = AssetFolder(requested);
            if (string.Equals(current, next, StringComparison.OrdinalIgnoreCase)) return current;
            MoveAll(current, next);
            return next;
        }

        internal static void Reconcile()
        {
            string root = UIAuthoringSettings.instance.GeneratedFolder;
            try { MoveAll(root, root); }
            catch (Exception exception) { Debug.LogError($"[UI] 同步生成脚本目录失败：{exception.Message}"); }
        }

        #endregion

        #region 私有逻辑

        private static void MoveAll(string current, string next)
        {
            var moves = new List<(string source, Route destination)>();
            var guids = new HashSet<string>(StringComparer.Ordinal);
            foreach (var file in OwnedScripts(current))
            {
                if (!guids.Add(file.guid))
                    throw new InvalidOperationException($"业务脚本 {file.guid} 存在重复的生成文件。");
                string business = AssetDatabase.GUIDToAssetPath(file.guid);
                if (string.IsNullOrEmpty(business) || !File.Exists(business))
                {
                    if (current != next)
                        throw new InvalidOperationException($"{file.path} 的业务脚本已丢失，请先清理该生成文件。");
                    continue;
                }

                Route route = GetRoute(next, business, file.guid);
                if (!string.Equals(file.path, route.Path, StringComparison.OrdinalIgnoreCase))
                {
                    if (File.Exists(route.Path))
                        throw new InvalidOperationException($"生成文件已存在：{route.Path}。");
                    moves.Add((file.path, route));
                }
            }

            foreach (var move in moves) PrepareRoute(move.destination);
            if (moves.Count == 0) return;
            int completed = 0;
            AssetDatabase.StartAssetEditing();
            try
            {
                for (; completed < moves.Count; completed++)
                    Move(moves[completed].source, moves[completed].destination.Path);
            }
            catch
            {
                for (int index = completed - 1; index >= 0; index--)
                {
                    var move = moves[index];
                    string error = AssetDatabase.MoveAsset(move.destination.Path, move.source);
                    if (!string.IsNullOrEmpty(error)) Debug.LogError($"[UI] 无法还原 {move.source}：{error}");
                }
                throw;
            }
            finally { AssetDatabase.StopAssetEditing(); }
        }

        private static void Move(string from, string to)
        {
            string problem = AssetDatabase.MoveAsset(from, to);
            if (!string.IsNullOrEmpty(problem)) throw new InvalidOperationException($"无法移动 {from}：{problem}");
        }

        private static IEnumerable<(string path, string guid)> OwnedScripts(string root, string pattern = "*.g.cs")
        {
            if (!Directory.Exists(root)) yield break;
            foreach (string file in Directory.EnumerateFiles(root, pattern, SearchOption.AllDirectories))
                if (IsOwned(file, out string guid)) yield return (file.Replace('\\', '/'), guid);
        }

        private static bool IsOwned(string path, out string guid)
        {
            Match match = SourceGuid.Match(path);
            guid = match.Success ? match.Groups[1].Value : null;
            if (!match.Success) return false;
            using var reader = File.OpenText(path);
            return reader.ReadLine() == GeneratedHeader;
        }

        #endregion

        #region 公共方法

        internal static void EnsureFolder(string path)
        {
            if (AssetDatabase.IsValidFolder(path)) return;
            int slash = path.LastIndexOf('/');
            string parent = path.Substring(0, slash);
            EnsureFolder(parent);
            if (string.IsNullOrEmpty(AssetDatabase.CreateFolder(parent, path.Substring(slash + 1))))
                throw new InvalidOperationException($"无法创建目录 {path}。");
        }

        internal static string AssetFolder(string value)
        {
            string path = value?.Trim().Replace('\\', '/').TrimEnd('/') ?? string.Empty;
            if (path == "Assets") return path;
            if (!path.StartsWith("Assets/", StringComparison.Ordinal) ||
                path.Split('/').Any(part => part.Length == 0 || part == "." || part == ".." ||
                    part.IndexOfAny(System.IO.Path.GetInvalidFileNameChars()) >= 0))
                throw new InvalidOperationException("请选择 Assets 下的有效目录。");
            return path;
        }

        #endregion
    }

    /// <summary>在业务脚本或程序集路由发生变更后同步 UI 生成文件。</summary>
    internal sealed class UIGeneratedScriptAssetChanges : AssetPostprocessor
    {
        private static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom)
        {
            bool affected = moved.Concat(movedFrom).Concat(deleted).Any(path => path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) &&
                !path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase));
            affected |= imported.Concat(deleted).Concat(moved).Concat(movedFrom).Any(path =>
                path.EndsWith(".asmdef", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".asmref", StringComparison.OrdinalIgnoreCase));
            if (!affected) return;
            EditorApplication.delayCall -= UIGeneratedScriptFiles.Reconcile;
            EditorApplication.delayCall += UIGeneratedScriptFiles.Reconcile;
        }
    }
}
