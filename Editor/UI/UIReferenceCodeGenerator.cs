using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using EasyFramework.UI;
using UnityEditor;
using UnityEngine;

namespace EasyFramework.Editor.UI
{
    /// <summary>从 Prefab 的 UIReference 数据生成可编译的 Key 常量。</summary>
    internal static class UIReferenceCodeGenerator
    {
        internal static string Generate(UIDisplay display, out List<string> staleUsages)
        {
            if (display == null) throw new ArgumentNullException(nameof(display));
            string scriptPath = display.ViewScriptPath;
            if (string.IsNullOrWhiteSpace(scriptPath) || !scriptPath.StartsWith("Assets/", StringComparison.Ordinal))
                throw new InvalidOperationException("请先为 Display 生成 View 脚本。");
            string className = Path.GetFileNameWithoutExtension(scriptPath) + "Keys";
            string outputPath = Path.ChangeExtension(scriptPath, null) + "Keys.g.cs";
            string fullPath = Path.GetFullPath(outputPath);
            var entries = new SortedDictionary<string, string>(StringComparer.Ordinal);
            foreach (UIReference marker in display.GetComponentsInChildren<UIReference>(true))
            {
                if (marker.GetComponentInParent<UIDisplay>(true) != display) continue;
                foreach (UIReferenceEntry entry in marker.Entries)
                {
                    if (entry == null || entry.Target == null || string.IsNullOrWhiteSpace(entry.Key))
                        throw new InvalidOperationException($"{marker.name} 存在未完成的引用，请先补齐 Key 和目标。");
                    string key = entry.Key.Trim();
                    string identifier = "Key_" + Sanitize(key);
                    if (entries.ContainsKey(identifier))
                        throw new InvalidOperationException($"引用 Key 重复或生成同名常量：{key}");
                    entries.Add(identifier, key);
                }
            }
            string previous = File.Exists(fullPath) ? File.ReadAllText(fullPath) : string.Empty;
            staleUsages = FindStaleUsages(previous, entries.Keys, className, fullPath);
            string source = BuildSource(display, className, entries);
            if (previous != source)
            {
                File.WriteAllText(fullPath, source, new UTF8Encoding(false));
                AssetDatabase.ImportAsset(outputPath, ImportAssetOptions.ForceUpdate);
            }
            return outputPath;
        }

        private static string BuildSource(UIDisplay display, string className,
            SortedDictionary<string, string> entries)
        {
            string fullName = (display.ViewTypeName ?? string.Empty).Split(',')[0].Trim();
            int dot = fullName.LastIndexOf('.');
            string nameSpace = dot > 0 ? fullName.Substring(0, dot) : UIScriptGenerator.DefaultNamespace;
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated>UIReference keys; regenerate from the UI workbench.</auto-generated>");
            source.AppendLine("namespace " + nameSpace);
            source.AppendLine("{");
            source.AppendLine("    public static class " + className);
            source.AppendLine("    {");
            foreach (KeyValuePair<string, string> entry in entries)
                source.AppendLine($"        public const string {entry.Key} = \"{Escape(entry.Value)}\";");
            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        private static List<string> FindStaleUsages(string previous,
            ICollection<string> current, string className, string generatedPath)
        {
            var stale = new List<string>();
            var old = Regex.Matches(previous, @"public const string (Key_[A-Za-z0-9_]+) =");
            foreach (Match match in old)
            {
                string identifier = match.Groups[1].Value;
                if (current.Contains(identifier)) continue;
                string usage = className + "." + identifier;
                foreach (string path in Directory.GetFiles(Application.dataPath, "*.cs", SearchOption.AllDirectories))
                {
                    if (string.Equals(path, generatedPath, StringComparison.OrdinalIgnoreCase)) continue;
                    if (File.ReadAllText(path).Contains(usage))
                        stale.Add($"{path}: {usage}");
                }
            }
            return stale;
        }

        private static string Sanitize(string key)
        {
            var result = new StringBuilder();
            foreach (char c in key)
                result.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            return result.ToString();
        }

        private static string Escape(string value)
        {
            var escaped = new StringBuilder(value.Length);
            foreach (char character in value)
            {
                switch (character)
                {
                    case '\\': escaped.Append("\\\\"); break;
                    case '"': escaped.Append("\\\""); break;
                    case '\n': escaped.Append("\\n"); break;
                    case '\r': escaped.Append("\\r"); break;
                    case '\t': escaped.Append("\\t"); break;
                    default:
                        if (char.IsControl(character)) escaped.Append("\\u").Append(((int)character).ToString("X4"));
                        else escaped.Append(character);
                        break;
                }
            }
            return escaped.ToString();
        }
    }
}
